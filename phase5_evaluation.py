"""
Phase 5: Comprehensive Evaluation, Attention Visualization, and Error Analysis
================================================================================
Description:
    Loads trained HierarchicalMuRIL model weights and performs full evaluation:
      1. Prints full sklearn classification report.
      2. Generates and saves confusion matrix heatmap ('confusion_matrix.png').
      3. Visualizes token-level word attention weights for sample sentences ('attention_viz_ex1.png', 'attention_viz_ex2.png').
      4. Conducts error analysis on misclassified test samples.
      5. Outputs final project performance summary table across all 4 models.

Dependencies:
    - phase2_data.joblib (Generated by phase2_preprocessing.py)
    - phase4_results.joblib (Generated by phase4_hierarchical.py)
    - hier_model.pt (Model weights saved by phase4_hierarchical.py)
    - phase2_preprocessing.py (Imports normalize_tanglish & TanglishDataset)
    - phase4_hierarchical.py (Imports HierarchicalMuRIL & test_hierarchical)

Outputs:
    - confusion_matrix.png: Saved heatmap image of test confusion matrix.
    - attention_viz_ex1.png: Attention weight plot for derogatory sample.
    - attention_viz_ex2.png: Attention weight plot for non-offensive sample.
"""

import os
import joblib
import torch
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from torch.utils.data import DataLoader
from transformers import AutoTokenizer
from sklearn.metrics import classification_report, confusion_matrix

from phase2_preprocessing import normalize_tanglish, TanglishDataset
from phase4_hierarchical import HierarchicalMuRIL, test_hierarchical

# Setup Device
DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
MAX_LEN = 128
BATCH_SIZE = 16

# ==============================================================================
# Step 3: Word Attention Visualization Function
# ==============================================================================
def visualize_attention(model, text: str, tokenizer, device, save_name: str = "attention_viz.png"):
    """
    Visualizes token-level attention weights learned by the word_attn layer of HierarchicalMuRIL.
    """
    model.eval()

    processed_text = normalize_tanglish(text)
    encoding = tokenizer(
        processed_text,
        return_tensors='pt',
        truncation=True,
        max_length=MAX_LEN
    )

    input_ids = encoding['input_ids'].to(device)
    attention_mask = encoding['attention_mask'].to(device)

    with torch.no_grad():
        encoder_outputs = model.encoder(input_ids=input_ids, attention_mask=attention_mask)
        last_hidden_state = encoder_outputs.last_hidden_state

        token_vecs = last_hidden_state[:, 1:, :]
        token_mask = attention_mask[:, 1:]

        attn_scores = model.word_attn(token_vecs).squeeze(-1)
        attn_scores = attn_scores.masked_fill(token_mask == 0, -1e9)
        attn_weights = torch.softmax(attn_scores, dim=-1).squeeze(0).cpu().numpy()

    tokens = tokenizer.convert_ids_to_tokens(input_ids[0][1:].cpu())

    plt.figure(figsize=(12, 4))
    sns.barplot(x=tokens, y=attn_weights, hue=tokens, legend=False, palette="viridis")
    plt.title(f"Word Attention Weights for Input: '{processed_text}'", fontsize=12, fontweight='bold')
    plt.xlabel("Tokens", fontsize=10, fontweight='bold')
    plt.ylabel("Attention Weight", fontsize=10, fontweight='bold')
    plt.xticks(rotation=45, ha='right', fontsize=10)
    plt.tight_layout()

    plt.savefig(save_name, dpi=300)
    print(f"✅ Saved attention visualization plot to '{save_name}'")
    plt.show()
    plt.close()


# ==============================================================================
# Main Execution Pipeline
# ==============================================================================
def main():
    p2_file = "phase2_data.joblib"
    p4_file = "phase4_results.joblib"
    model_weight_file = "hier_model.pt"

    if not os.path.exists(p2_file) or not os.path.exists(p4_file) or not os.path.exists(model_weight_file):
        raise FileNotFoundError(f"Missing required artifacts. Please run phases 1-4 first!")

    print("Loading data, results, and trained model weights...")
    data_p2 = joblib.load(p2_file)
    data_p4 = joblib.load(p4_file)

    test_df       = data_p2['test_df']
    class_weights = data_p2['class_weights']
    label2id      = data_p2['label2id']
    id2label      = {v: k for k, v in label2id.items()}
    target_names  = list(label2id.keys())

    test_f1_xlmr  = data_p4['test_f1_xlmr']
    test_f1_muril = data_p4['test_f1_muril']
    test_f1_word  = data_p4['test_f1_word']
    test_f1_hier  = data_p4['test_f1_hier']

    # Load Model Architecture & Weights
    tokenizer = AutoTokenizer.from_pretrained("google/muril-base-cased")
    test_dataset = TanglishDataset(test_df, tokenizer, max_len=MAX_LEN)
    test_loader  = DataLoader(test_dataset, batch_size=BATCH_SIZE, shuffle=False)

    hier_model = HierarchicalMuRIL().to(DEVICE)
    hier_model.load_state_dict(torch.load(model_weight_file, map_location=DEVICE))
    print("✅ Successfully loaded trained HierarchicalMuRIL model weights.")

    # --------------------------------------------------------------------------
    # 1. Full Classification Report
    # --------------------------------------------------------------------------
    test_f1_hier, hier_preds, hier_labels, _ = test_hierarchical(hier_model, test_loader)
    print("\n" + "=" * 80)
    print(" 📊 DETAILED CLASSIFICATION REPORT FOR PROPOSED HIERARCHICAL MURIL MODEL")
    print("=" * 80)
    print(classification_report(hier_labels, hier_preds, target_names=target_names, digits=4, zero_division=0))

    # --------------------------------------------------------------------------
    # 2. Confusion Matrix Plotting
    # --------------------------------------------------------------------------
    cm = confusion_matrix(hier_labels, hier_preds)
    plt.figure(figsize=(10, 8))
    sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', xticklabels=target_names, yticklabels=target_names)
    plt.xlabel('Predicted Label', fontsize=12, fontweight='bold')
    plt.ylabel('True Label', fontsize=12, fontweight='bold')
    plt.title('Hierarchical MuRIL Confusion Matrix (Tanglish Hate Speech)', fontsize=14, fontweight='bold')
    plt.xticks(rotation=45, ha='right', fontsize=10)
    plt.yticks(rotation=0, fontsize=10)
    plt.tight_layout()
    plt.savefig("confusion_matrix.png", dpi=300)
    print("✅ Saved confusion matrix plot to 'confusion_matrix.png'")
    plt.close()

    # --------------------------------------------------------------------------
    # 3. Attention Visualizations
    # --------------------------------------------------------------------------
    print("\nGenerating Attention Visualizations...")
    visualize_attention(hier_model, "dei loosu poda get out da", tokenizer, DEVICE, save_name="attention_viz_ex1.png")
    visualize_attention(hier_model, "super performance da excellent work", tokenizer, DEVICE, save_name="attention_viz_ex2.png")

    # --------------------------------------------------------------------------
    # 4. Error Analysis
    # --------------------------------------------------------------------------
    test_df_analysis = test_df.copy()
    test_df_analysis['predicted'] = hier_preds
    errors_df = test_df_analysis[test_df_analysis['label'] != test_df_analysis['predicted']]

    total_samples = len(test_df_analysis)
    error_count   = len(errors_df)
    error_rate    = (error_count / total_samples) * 100

    print("\n🔍 MISCLASSIFICATION SUMMARY:")
    print(f"  - Total Test Samples:   {total_samples}")
    print(f"  - Misclassified Count:  {error_count}")
    print(f"  - Overall Error Rate:   {error_rate:.2f}%\n")

    print("--- 10 Sample Misclassified Rows ---")
    for _, row in errors_df.head(10).iterrows():
        true_str = id2label[row['label']]
        pred_str = id2label[row['predicted']]
        print(f"Original Text : {row['text']}")
        print(f"Processed Text: {row['processed']}")
        print(f"True Label    : {true_str} ({row['label']})")
        print(f"Predicted     : {pred_str} ({row['predicted']})")
        print("-" * 80)

    # --------------------------------------------------------------------------
    # 5. Final Performance Summary Table
    # --------------------------------------------------------------------------
    final_summary_df = pd.DataFrame({
        "Model Architecture": [
            "Baseline A: XLM-RoBERTa (Sentence-Only)",
            "Baseline B: MuRIL (Sentence-Only)",
            "Ablation Model: MuRIL (Word-Attention Only)",
            "Proposed Model: Hierarchical MuRIL (Sentence + Word Fusion)"
        ],
        "Test Macro F1 Score": [
            f"{test_f1_xlmr:.4f}",
            f"{test_f1_muril:.4f}",
            f"{test_f1_word:.4f}",
            f"{test_f1_hier:.4f}"
        ]
    })

    print("\n" + "=" * 80)
    print("     HIERARCHICAL HATE SPEECH DETECTION IN TANGLISH - FINAL SUMMARY TABLE     ")
    print("=" * 80)
    print(final_summary_df.to_string(index=False))
    print("=" * 80)

if __name__ == "__main__":
    main()
